function distance = sage_parameter_step(current,previous,cfg)
% Maximum dimensionless change over ALL parameters of ALL paths.
steps = [abs([current.tau]-[previous.tau])/cfg.scale(1), ...
    abs([current.phi]-[previous.phi])/cfg.scale(2), ...
    abs([current.fdopp]-[previous.fdopp])/cfg.scale(3), ...
    abs([current.amp]-[previous.amp])/max(norm([previous.amp]),1)];
distance = max(steps);
end
